   // PASSIVE MOB SPAWNING — WEIGHTS
   // ============================================================================

   public java.util.Map<org.bukkit.entity.EntityType, Integer> getPassiveMobSpawnWeights() {
      java.util.Map<org.bukkit.entity.EntityType, Integer> weights = new java.util.LinkedHashMap<>();
      org.bukkit.configuration.ConfigurationSection section = this.config.getConfigurationSection("passive-mob-spawning.mob-weights");
      if (section != null) {
         for (String key : section.getKeys(false)) {
            try {
               org.bukkit.entity.EntityType type = org.bukkit.entity.EntityType.valueOf(key.toUpperCase());
               int weight = section.getInt(key, 0);
               if (weight > 0) weights.put(type, weight);
            } catch (IllegalArgumentException ignored) {
               this.plugin.getLogger().warning("[WerePires] Unknown entity type in passive-mob-spawning.mob-weights: " + key);
            }
         }
      }
      if (weights.isEmpty()) {
         weights.put(org.bukkit.entity.EntityType.COW, 30);
         weights.put(org.bukkit.entity.EntityType.PIG, 30);
         weights.put(org.bukkit.entity.EntityType.SHEEP, 25);
         weights.put(org.bukkit.entity.EntityType.CHICKEN, 15);
      }
      return weights;
   }

   public boolean isLocationWithinBorder(double x, double z) {
      return x >= this.getOakhurstMinX() && x <= this.getOakhurstMaxX() && z >= this.getOakhurstMinZ() && z <= this.getOakhurstMaxZ();
   }

   public List<String> validateConfiguredLocations(BeaconManager beaconManager) {
      List<String> warnings = new ArrayList<>();
      double townX = this.getOakhurstTownCenterX();
      double townZ = this.getOakhurstTownCenterZ();
      if (!this.isLocationWithinBorder(townX, townZ)) {
         warnings.add("Town center (" + (int)townX + ", " + (int)townZ + ")");
      }

      World world = this.plugin.getWorld();
      if (world != null) {
         Location vampireSpawn = this.getVampireRespawnLocation(world);
         if (vampireSpawn != null && !this.isLocationWithinBorder(vampireSpawn.getX(), vampireSpawn.getZ())) {
            warnings.add("Vampire respawn (" + vampireSpawn.getBlockX() + ", " + vampireSpawn.getBlockZ() + ")");
         }

         for (Location loc : this.getTomeChestLocations()) {
            if (loc != null && !this.isLocationWithinBorder(loc.getX(), loc.getZ())) {
               warnings.add("Tome chest at (" + loc.getBlockX() + ", " + loc.getBlockZ() + ")");
            }
         }
      }

      if (beaconManager != null) {
         for (BeaconSite beacon : beaconManager.getAllBeacons()) {
            Location loc = beacon.getLocation();
            if (loc == null) {
               // Beacon's world isn't loaded/resolving — skip (and surface it).
               warnings.add("Beacon '" + beacon.getName() + "' — world '" + beacon.getWorldName() + "' not loaded");
               continue;
            }
            if (!this.isLocationWithinBorder(loc.getX(), loc.getZ())) {
               warnings.add("Beacon '" + beacon.getName() + "' (" + loc.getBlockX() + ", " + loc.getBlockZ() + ")");
            }
         }
      }

      return warnings;
   }
