   public void loadConfig() {
      this.plugin.saveDefaultConfig();
      this.plugin.reloadConfig();
      // Merge any newly-added default keys (from plugin updates) into the on-disk config
      // without overwriting the values already set there. This keeps the in-game config
      // editor showing every available setting, even on servers generated by older builds.
      this.plugin.getConfig().options().copyDefaults(true);
      this.plugin.saveConfig();
      this.config = this.plugin.getConfig();
   }

